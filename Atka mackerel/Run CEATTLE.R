# Code to run the atka mackerel assessment in CEATTLE
# model is a single sex, single-species model
# uses dev_srr branch
# https://github.com/grantdadams/Rceattle/tree/dev_srr

# DATA
# - Fishery catch
# - Fishery age composition
# - Fishery weight-at-age
